from dataclasses import dataclass, field
from enum import Enum
import json
from typing import Any


@dataclass
class TextDelta:
    """
    Represents a small piece of text received from the LLM.

    WHY DO WE NEED THIS?

    When streaming is enabled, the LLM doesn't send the entire
    response at once.

    For example, it might send:

        Chunk 1: "Python"
        Chunk 2: " is"
        Chunk 3: " a programming"
        Chunk 4: " language."

    Each chunk is a TextDelta.

    The application can display each piece immediately instead
    of waiting for the entire response.
    """

    content: str

    def __str__(self):
        # Allows us to use str(text_delta) to get its actual text.
        return self.content


class StreamEventType(str, Enum):
    """
    Defines the different kinds of events our LLMClient can produce.

    WHY DO WE NEED THIS?

    The LLM can produce different things during a response:
    normal text, tool calls, errors, and so on.

    Instead of making the Agent inspect raw OpenAI SDK objects,
    we give it a consistent event type to identify what happened.
    """

    # A new piece of normal assistant text has arrived.
    TEXT_DELTA = "text_delta"

    # The LLM has finished producing its response.
    MESSAGE_COMPLETE = "message_complete"

    # Something went wrong while communicating with the LLM.
    ERROR = "error"

    # The LLM has started requesting a tool.
    TOOL_CALL_START = "tool_call_start"

    # Another piece of the tool call's arguments has arrived.
    TOOL_CALL_DELTA = "tool_call_delta"

    # All the pieces of the tool call have been received.
    TOOL_CALL_COMPLETE = "tool_call_complete"


@dataclass
class TokenUsage:
    """
    Stores token consumption information for an LLM request.

    prompt_tokens:
        Tokens sent TO the LLM.

    completion_tokens:
        Tokens generated BY the LLM.

    total_tokens:
        Total tokens consumed by the request.

    cached_tokens:
        Input tokens served from the provider's prompt cache,
        when the provider reports this information.

    WHY DO WE NEED THIS?

    An Agent may make multiple LLM requests during a single task.

    We can use TokenUsage to track how many tokens the entire
    task consumed.
    """

    prompt_tokens: int = 0
    completion_tokens: int = 0
    total_tokens: int = 0
    cached_tokens: int = 0

    def __add__(self, other: TokenUsage):
        """
        Allows us to add the usage of two different LLM requests.

        Example:

            first_request = TokenUsage(prompt_tokens=100)
            second_request = TokenUsage(prompt_tokens=200)

            total = first_request + second_request

        The resulting total has 300 prompt tokens.
        """

        return TokenUsage(
            prompt_tokens=self.prompt_tokens + other.prompt_tokens,
            completion_tokens=self.completion_tokens + other.completion_tokens,
            total_tokens=self.total_tokens + other.total_tokens,
            cached_tokens=self.cached_tokens + other.cached_tokens,
        )


@dataclass
class ToolCallDelta:
    """
    Represents an incomplete piece of a tool call received during streaming.

    WHY DO WE NEED THIS?

    Tool calls can also be streamed in multiple chunks.

    For example, the LLM might send the arguments like this:

        Chunk 1: '{"path":'
        Chunk 2: '"main.py"'
        Chunk 3: '}'

    Each incoming piece is represented by a ToolCallDelta.

    tool_call_id:
        Identifies this particular tool call. We need this ID later
        to connect the tool's result to the original request.

    tool_name:
        The name of the tool the LLM wants to invoke.

    arguments_delta:
        The latest piece of the tool's arguments.
        This is only a fragment, not necessarily valid JSON yet.
    """

    tool_call_id: str
    tool_name: str | None = None
    arguments_delta: str = ""


@dataclass
class ToolCall:
    """
    Represents a complete tool call received from the LLM.

    The difference between ToolCallDelta and ToolCall:

        ToolCallDelta -> An incomplete piece arriving during streaming.

        ToolCall      -> The complete tool call after all pieces
                         have been collected.

    Example of a completed tool call:

        call_id = "call_123"
        name = "read_file"
        arguments = {"path": "main.py"}

    The Agent can now use this information to execute the tool.
    """

    tool_call_id: str
    tool_name: str | None = None
    arguments: dict[str, Any] = field(default_factory=dict)


@dataclass
class StreamEvent:
    """
    Represents one update received from the LLMClient.

    The Agent uses the `type` field to understand what happened,
    and reads the corresponding field to get the details.

    For example:

        TEXT_DELTA:
            text_delta contains the newly received text.

        TOOL_CALL_START / TOOL_CALL_DELTA:
            tool_call_delta contains information about the
            tool call being generated.

        TOOL_CALL_COMPLETE:
            tool_call contains the complete tool request,
            including its arguments.

        MESSAGE_COMPLETE:
            The LLM has finished its response. We may also
            receive the finish reason and token usage.

        ERROR:
            error contains the error message.

    Only the fields relevant to a particular event need to be set.
    """

    # Tells the Agent what kind of event it has received.
    type: StreamEventType

    # The text received from the LLM.
    # During streaming, this contains the latest text chunk.
    text_delta: TextDelta | None = None

    # Contains the error message if the LLM request failed.
    error: str | None = None

    # Explains why the LLM stopped generating.
    # For example: "stop" (normal completion), "tool_calls" or "length".
    finish_reason: str | None = None

    # Contains information about a tool call while it is being generated.
    # For example, the tool name or the latest piece of its arguments.
    tool_call_delta: ToolCallDelta | None = None

    # Contains the complete tool call after all its argument chunks
    # have been received and combined.
    tool_call: ToolCall | None = None

    # Non-streaming responses can contain multiple complete tool calls.
    tool_calls: list[ToolCall] | None = None

    # Contains token consumption information for the LLM request.
    usage: TokenUsage | None = None


def parse_tool_call_arguments(arguments_str: str) -> dict[str, Any]:
    """
    Converts the JSON string received from the LLM into a Python dictionary.

    WHY DO WE NEED THIS?

    The LLM sends tool arguments as JSON text.

    For example, it might send:

        '{"path": "main.py"}'

    But our Python application needs a dictionary:

        {"path": "main.py"}

    json.loads() performs this conversion.

    If the arguments are empty, we return an empty dictionary.

    If the JSON is invalid, we preserve the original text inside
    a dictionary rather than losing the information.
    """

    if not arguments_str:
        return {}

    try:
        return json.loads(arguments_str)

    except json.JSONDecodeError:
        return {"raw_arguments": arguments_str}
