import json
from pathlib import Path
from typing import AsyncGenerator

from agent.events import AgentEvent, AgentEventType
from client.llm_client import LLMClient
from client.response import StreamEventType, ToolCall
from config.config import Config
from context.manager import ContextManager
from tools.registry import create_default_registry


class Agent:
    """
    Coordinates the LLM, tools, and conversation history to complete a task.
    """

    def __init__(self, config: Config):
        self.config = config
        self.client = LLMClient(config)
        self.context_manager = ContextManager(config)
        self.tool_registry = create_default_registry()

    async def run(self, message: str) -> AsyncGenerator[AgentEvent, None]:
        """
        Process a user message and yield events describing the interaction.

        The actual LLM and tool-calling work happens inside _agentic_loop().
        """

        # Yield an event indicating that the agent has started processing the message.
        yield AgentEvent.agent_start(message)

        # Add the user's message to the context manager to keep track of the conversation history.
        self.context_manager.add_user_message(message)

        final_response: str | None = None

        # Forward events produced by the agentic loop to the application.
        async for event in self._agentic_loop():
            yield event

            # If the event indicates that the text generation is complete, store the final response.
            if event.type == AgentEventType.TEXT_COMPLETE:
                final_response = event.data.get("content")

        yield AgentEvent.agent_end(final_response)

    async def _agentic_loop(self) -> AsyncGenerator[AgentEvent, None]:
        """
        Repeatedly communicate with the LLM and execute requested tools
        until the LLM produces a final response or the turn limit is reached.
        """

        max_turns = self.config.max_turns

        for turn in range(max_turns):
            # Collect all text chunks belonging to this LLM response.
            response_text = ""

            # Get the schemas of all tools currently available to the Agent.
            tool_schemas = self.tool_registry.get_schemas()

            # Collect all the tool calls requested by the LLM, so that we can execute them later on
            tool_calls: list[ToolCall] = []

            # Send the conversation history and available tools to the LLM.
            async for event in self.client.chat_completion(
                self.context_manager.get_messages(),
                tools=tool_schemas if tool_schemas else None,
            ):
                # The LLM is streaming normal assistant text.
                if event.type == StreamEventType.TEXT_DELTA:
                    if event.text_delta:
                        content = event.text_delta.content
                        response_text += content

                        # Yield an event indicating that a new chunk of text has been generated by the LLM, so that the TUI can display it in real-time.
                        yield AgentEvent.text_delta(content)

                # A streaming tool call has been fully reconstructed.
                elif event.type == StreamEventType.TOOL_CALL_COMPLETE:
                    if event.tool_call:
                        tool_calls.append(event.tool_call)

                # Forward errors from the LLM client to the application.
                elif event.type == StreamEventType.ERROR:
                    yield AgentEvent.agent_error(
                        event.error or "Unknown error occurred"
                    )

            # Save the assistant's response in conversation history.
            #
            # If the assistant requested tools, we must also save those
            # requests. This lets the LLM see which tools it previously called
            # when we send the tool results in the next turn.
            self.context_manager.add_assistant_message(
                response_text or None,
                (
                    [
                        {
                            "id": tc.tool_call_id,
                            "type": "function",
                            "function": {
                                "name": tc.tool_name,
                                # Chat Completions expects arguments as a JSON string.
                                "arguments": json.dumps(tc.arguments),
                            },
                        }
                        for tc in tool_calls
                    ]
                    if tool_calls
                    else None
                ),
            )

            if response_text:
                # Yield the final response text to the application.
                yield AgentEvent.text_complete(response_text)

            # Break the agentic loop if the LLM did not request any tool calls.
            if not tool_calls:
                break

            # Execute all tool calls requested by the LLM, one by one.
            for tool_call in tool_calls:
                # Yield an event indicating that the agent has started executing a tool call, so that the TUI can display a message accordingly.
                yield AgentEvent.tool_call_start(
                    tool_call.tool_call_id,
                    tool_call.tool_name,
                    tool_call.arguments,
                )

                # Execute the tool call and get the result.
                result = await self.tool_registry.invoke(
                    tool_call.tool_name,
                    tool_call.arguments,
                    self.config.cwd,
                )

                # Yield the result of the tool call
                yield AgentEvent.tool_call_complete(
                    tool_call.tool_call_id,
                    tool_call.tool_name,
                    result,
                )

                # Save the result of the tool call to the conversation history, so that the LLM can use these results as context in the next LLM request.
                self.context_manager.add_tool_result(
                    tool_call.tool_call_id,
                    result.to_model_output(),
                )

    async def __aenter__(self) -> Agent:
        """Initialize the agent's session before use.

        Called automatically when entering an `async with` block.
        Returns the initialized Agent instance.
        """
        return self

    async def __aexit__(
        self,
        exc_type,
        exc_val,
        exc_tb,
    ) -> None:
        """Clean up the agent's resources when leaving the `async with` block.

        Called automatically when the block exits, whether normally
        or because of an exception.
        """
        if self.client:
            await self.client.close()
            self.client = None
